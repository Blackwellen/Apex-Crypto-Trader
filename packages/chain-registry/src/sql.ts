// Renders the seed migration FROM the TypeScript registry. Output is deterministic; a test asserts the committed file is in sync.
import { CAPABILITIES } from '@apex/contracts';
import type { ChainRecord, VerifiedChainRecord } from '@apex/contracts';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const nul = (s: string | undefined) => (s === undefined ? 'null' : q(s));
function stable(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(stable);
  if (v && typeof v === 'object') return Object.fromEntries(Object.keys(v as object).sort().map((k) => [k, stable((v as Record<string, unknown>)[k])]));
  return v;
}
export function detailsOf(r: ChainRecord): Record<string, unknown> {
  const v = r as Partial<VerifiedChainRecord>;
  return stable({ rpcCandidates: r.rpcCandidates, verifiedFrom: v.verifiedFrom ?? [], unverified: v.unverified ?? true, unverifiedFields: v.unverifiedFields ?? ['provenance'], meta: v.meta ?? {} }) as Record<string, unknown>;
}

export const SEED_HEADER = `-- 0100_seed_chain_registry.sql
-- GENERATED by packages/chain-registry (pnpm --filter @apex/chain-registry gen:sql) from the TypeScript registry. DO NOT EDIT BY HAND.
-- A test (packages/chain-registry/test/sql-sync.test.ts) fails if this file drifts from buildRegistry().
-- Every chain is seeded enabled=false. Capabilities are PENDING/UNSUPPORTED, or READ_ONLY only where a real live read was recorded
-- (docs/evidence/chains-a-live-reads.md). Nothing is seeded CERTIFIED (certified_needs_evidence also forbids it without evidence).
`;

export function renderSeedSql(records: readonly ChainRecord[]): string {
  const out: string[] = [SEED_HEADER, ''];
  for (const r of records) {
    const details = JSON.stringify(detailsOf(r));
    out.push(
      `insert into chain_registry(id, namespace, chain_ref, family, name, is_testnet, native_symbol, native_decimals, finality_model, address_format, explorer_url, enabled, details) values (` +
      `${q(r.id)}, ${q(r.namespace)}, ${q(r.chainRef)}, ${q(r.family)}, ${q(r.name)}, ${r.isTestnet}, ${q(r.nativeSymbol)}, ${r.nativeDecimals}, ${q(r.finalityModel)}, ${q(r.addressFormat)}, ${nul(r.explorerUrl)}, false, ${q(details)}::jsonb)\n` +
      `on conflict (id) do update set namespace = excluded.namespace, chain_ref = excluded.chain_ref, family = excluded.family, name = excluded.name, is_testnet = excluded.is_testnet,\n` +
      `  native_symbol = excluded.native_symbol, native_decimals = excluded.native_decimals, finality_model = excluded.finality_model, address_format = excluded.address_format,\n` +
      `  explorer_url = excluded.explorer_url, details = excluded.details;   -- enabled is deliberately NOT overwritten`);
    const rows = CAPABILITIES.map((c) => {
      const cap = r.capabilities[c];
      if (cap.status === 'CERTIFIED' && !cap.evidenceRef) throw new Error(`${r.id}.${c}: CERTIFIED without evidenceRef`);
      return `  (${q(r.id)}, ${q(c)}, ${q(cap.status)}, ${nul(cap.evidenceRef)})`;
    });
    out.push(`insert into chain_capabilities(chain_id, capability, status, evidence_ref) values\n${rows.join(',\n')}\n` +
      `on conflict (chain_id, capability) do update set status = excluded.status, evidence_ref = excluded.evidence_ref, updated_at = now()\n  where chain_capabilities.status <> 'CERTIFIED';`, '');
  }
  out.push('');
  return out.join('\n');
}
